"""Response models for the orchestrator API."""

from __future__ import annotations

import math
from typing import Any

from pydantic import BaseModel, Field, model_validator


def _json_safe_nonfinite(value: Any) -> Any:
    """Replace non-finite floats that Starlette cannot JSON-render."""
    if isinstance(value, float):
        return value if math.isfinite(value) else 0.0
    if isinstance(value, BaseModel):
        _sanitize_model_nonfinite(value)
        return value
    if isinstance(value, dict):
        return {key: _json_safe_nonfinite(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_json_safe_nonfinite(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_json_safe_nonfinite(item) for item in value)
    return value


def _sanitize_model_nonfinite(model: BaseModel) -> None:
    for field in model.__class__.model_fields:
        current = getattr(model, field)
        safe = _json_safe_nonfinite(current)
        if safe is not current:
            setattr(model, field, safe)


class ToolTiming(BaseModel):
    """Per-tool invocation timing record."""

    tool_name: str = Field(..., description="Name of the tool invoked")
    elapsed_ms: float = Field(default=0.0, description="Wall-clock time for this invocation")
    success: bool = Field(default=True, description="Whether the invocation succeeded")
    output_tokens: int = Field(default=0, description="Estimated tokens in tool output (~len/4)")


class DelegationEvent(BaseModel):
    """Record of a delegation that occurred during request processing."""

    from_role: str = Field(..., description="Role that delegated")
    to_role: str = Field(..., description="Role that received delegation")
    interaction_type: str = Field(
        default="delegate",
        description="Interaction type: delegate, consult, verify, or route",
    )
    task_summary: str = Field(default="", description="What was delegated")
    success: bool | None = Field(
        default=None, description="Whether delegated work succeeded"
    )
    elapsed_ms: float = Field(default=0.0, description="Time spent on delegated work")
    tokens_generated: int = Field(default=0, description="Tokens generated by delegate")


def _omit_when_none() -> dict[str, Any]:
    """``exclude_if`` (pydantic >= 2.11) keeps a new optional field out of the
    serialized body when unset, so responses to requests that never asked for it
    stay byte-identical. On older pydantic the key is emitted as null instead."""
    import pydantic

    try:
        major, minor = (int(x) for x in pydantic.VERSION.split(".")[:2])
    except ValueError:
        return {}
    if (major, minor) >= (2, 11):
        return {"exclude_if": lambda value: value is None}
    return {}


