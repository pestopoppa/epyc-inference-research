#!/usr/bin/env python3
"""census_update.py -- DETERMINISTIC (no LLM) MI210 served-kernel bandwidth census updater.

    python3 -m autokernel.loop.census_update --result <RESULT.json> [--row ID]
        [--census census/mi210_bandwidth_census.json] [--program program.md] [--doc <md with generated block>]
        [--seeds-out DIR] [--dry-run]

Called at every AutoKernel result-filing boundary (epyc-root scripts/coordination/akloop/ak_runend.py, step 4).
It parses the filed row's RESULT.json for per-op timings, recomputes the effective GB/s and the ranking, and updates the
census JSON. It then regenerates the markdown table inside the BW-CENSUS generated block and appends one journal line
per moved kernel to program.md (section `## Learnings — bandwidth census journal (generated)`).

Rules (operator 2026-11-22):
- below FLOOR (1 TB/s) is an `open_surface`;
- a change within NOISE is not a move;
- re-applying the same RESULT sha is a no-op (idempotent);
- an open surface with no linked seed gets a seed stub;
- a seed whose every linked record reaches max(floor, target) is marked `done`.

Recognised RESULT shapes:
- `op.cells_us["<M>x<K>:n<N>"][arm]` (Q8_0 MUL_MAT rows, e.g. ak-q8wv-split16-*). Bytes are M*K*34/32. The served
  arm is the first present of V, ON, N, OFF.
- `op.table["<op>:n<N>"]{us_on,gbps_on}` (MUL_MAT_ID rows, e.g. ak-mmid-split16-*). Bytes are gbps_on*us_on*1e3.
Anything else yields no records, which is reported and is not an error.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys

from .census_extract import (  # noqa: F401  re-exported: callers/tests address these via census_update
    A3B_CPU_FAMILY_BYTES, CPU_MODEL_ALIAS, CPU_MODEL_BY_ID, MMID_CLASS, Q8_SHAPE_CLASS, SERVED_N, TRACE_DENSE_BYTES,
    TRACE_Q8_CLASS, cpu_config, extract, extract_cpu, extract_trace)

HERE = os.path.dirname(os.path.abspath(__file__))
CENSUS = os.path.join(HERE, "census", "mi210_bandwidth_census.json")
PROGRAM = os.path.join(HERE, "program.md")
FLOOR, TARGET, CEILING, NOISE = 1000.0, 1200.0, 1500.0, 0.03
# Profiling-unit rule: pick the unit by arithmetic intensity (FLOP/byte) vs the ridge point = peak compute / peak BW.
# MI210: 181 TFLOP/s (f16 MFMA; int8 same rate) / 1500 GB/s measured ceiling = ~121 FLOP/B. CPU (EPYC 9655 half-48t):
# ~8.3 TFLOP/s fp32 AVX-512 (DERIVED: 48c x 2.7GHz x 64) / 259.8 GB/s measured read-sum = ~32 FLOP/B.
UNITS = ("GB/s", "TFLOP/s")
RIDGE_FLOP_PER_BYTE = {"gpu": 181e12 / 1500e9, "cpu": 8.3e12 / 259.8e9}


def unit_for(flops: float, nbytes: float, device: str = "gpu") -> str:
    """TFLOP/s when arithmetic intensity >= ridge (compute-bound), else GB/s (memory-bound)."""
    return "TFLOP/s" if nbytes > 0 and flops / nbytes >= RIDGE_FLOP_PER_BYTE[device] else "GB/s"


def validate_unit(rec: dict) -> list[str]:
    """Errors for a census record. unit is nullable (pre-2026-11-22 rows); flops_per_call optional (bytes-only = BW)."""
    errs, unit = [], rec.get("unit")
    if unit is not None and unit not in UNITS:
        errs.append(f"unit {unit!r} not in {UNITS}")
    f, b = rec.get("flops_per_call"), rec.get("bytes_per_call")
    if unit is not None and f and b:
        want = unit_for(f, b, rec.get("device", "gpu"))
        if want != unit:
            errs.append(f"intensity {f / b:.1f} FLOP/B vs ridge {RIDGE_FLOP_PER_BYTE[rec.get('device', 'gpu')]:.0f}: "
                        f"must be judged in {want}, record says {unit}")
    return errs


JOURNAL_HEAD = "## Learnings — bandwidth census journal (generated by census_update.py; deterministic, do not hand-edit)"
BEGIN, END = "<!-- BW-CENSUS:BEGIN generated by census_update.py -->", "<!-- BW-CENSUS:END -->"
# CPU (EPYC 9655 Zen 5, NPS4). Ceiling = measured read-sum, NOT a guess. half-48t: 259.8 GB/s same-window read-sum
# (q38p1-c13-20261117-r4, 2026-11-18). quarter-24t: 112.9 GB/s MEASURED (AK-CPU-QUARTER-READCEIL, filed 2026-11-23):
# first valid pass of in-row unit ceil-pre of ak-a3b-cpu-mmid-gateup-ubench-20261122-r2 -- bench_readbw sha 9e379493,
# q2 (cpus 48-71, membind 2), 5 runs 110.8-120.2, median 112.9, CV 3.24 %, SMT-probe p50 0.74 %, ceil-post 113.4
# (post-drift 0.44 %). Replaces the derived 129.9 (= half-48t / 2), which overstated the quarter by 15 %.
CPU_DEFAULTS = {"flag_frac": 0.75, "target_frac": 0.80,
                "ceiling_gbps": {"half-48t": 259.8, "quarter-24t": 112.9},
                "ceiling_source": {"half-48t": "measured: q38p1-c13-20261117-r4 same-window bench_readbw read-sum",
                                   "quarter-24t": "measured: AK-CPU-QUARTER-READCEIL ubench-r2 ceil-pre bench_readbw 9e379493 q2"}}
def sha256(path: str) -> str:
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def empty_census() -> dict:
    return {"cpu": json.loads(json.dumps(CPU_DEFAULTS)), "schema": "epyc.autokernel.bw_census.v1", "floor_gbps": FLOOR, "target_gbps": TARGET,
            "ceiling_gbps": CEILING, "noise_frac": NOISE, "records": {}, "seeds": {}, "seed_stubs": [],
            "applied": []}


def rid(o: dict) -> str:
    if o.get("device") == "cpu":
        return f"cpu|{o['model']}|{o['kernel_class']}|{o['shape']}|n{o['n']}"
    return f"{o['model']}|{o['kernel_class']}|{o['shape']}|n{o['n']}"


def gbps(b: float, us: float) -> float:
    return round(b / (us * 1e3), 1) if us > 0 else 0.0


def recoverable_ms(r: dict, target: float) -> float:
    ideal_us = r["bytes_per_call"] / (target * 1e3)
    return round(max(0.0, r["us_per_call"] - ideal_us) * r["calls_per_round"] / 1e3, 3)


def rerank(c: dict) -> None:
    recs = c["records"]
    cpu = c.setdefault("cpu", json.loads(json.dumps(CPU_DEFAULTS)))
    for r in recs.values():
        r["gbps"] = gbps(r["bytes_per_call"], r["us_per_call"])
        floor, target = c["floor_gbps"], c["target_gbps"]
        if r.get("device") == "cpu":
            ceil = cpu["ceiling_gbps"].get(r.get("config", ""), 0.0)
            floor, target = cpu["flag_frac"] * ceil, cpu["target_frac"] * ceil
            r["ceiling_gbps"] = ceil
            r["frac_of_ceiling"] = round(r["gbps"] / ceil, 3) if ceil else None
        r["status"] = ("stale" if r.get("stale") else "no_ceiling" if floor <= 0
                       else "open_surface" if r["gbps"] < floor else "ok")
        r["recoverable_ms_per_round"] = recoverable_ms(r, target) if target > 0 else 0.0
    for dev in ("gpu", "cpu"):  # ranks are per device
        order = sorted((k for k in recs if recs[k].get("device", "gpu") == dev),
                       key=lambda k: (-recs[k]["recoverable_ms_per_round"], k))
        for i, k in enumerate(order, 1):
            recs[k]["rank"] = i


def link_seeds(c: dict) -> list[str]:
    """Mark seeds done and emit stubs for unlinked open surfaces. Returns journal fragments."""
    notes = []
    recs = c["records"]
    for sid, s in sorted(c["seeds"].items()):
        linked = [r for k, r in recs.items() if all(r.get(f) == v for f, v in s.get("match", {}).items())
                  and r["n"] in s.get("n", sorted(SERVED_N))]
        bar = float(s.get("target_gbps", c["floor_gbps"]))
        if s.get("device", "gpu") == "gpu":
            bar = max(c["floor_gbps"], bar)
        if linked and s.get("status") != "done" and all(r["gbps"] >= bar for r in linked):
            s["status"] = "done"
            notes.append(f"seed {sid} DONE (all {len(linked)} linked records >= {bar:.0f} GB/s)")
        for r in linked:
            r["seed"] = sid
    have = {x["record"] for x in c["seed_stubs"]}
    for k in sorted(recs):
        r = recs[k]
        if r["status"] == "open_surface" and not r.get("seed") and k not in have:
            c["seed_stubs"].append({"record": k, "gbps": r["gbps"], "source_row": r["source_row"]})
            notes.append(f"seed stub for {k} ({r['gbps']:.0f} GB/s < floor, no linked seed)")
    return notes


def apply(c: dict, obs: list[dict], row: str, sha: str, measured_at: str) -> list[str]:
    """Pure-ish: mutate census c, return journal lines. No-op when sha already applied."""
    if any(a["sha256"] == sha for a in c["applied"]):
        return []
    rerank(c)
    before = {k: (r["gbps"], r["rank"]) for k, r in c["records"].items()}
    moved = []
    for o in obs:
        o = dict(o, unit=o.get("unit") or "GB/s")  # every census extractor emits bytes/us => GB/s; flops rows set unit
        if errs := validate_unit(o):
            raise ValueError(f"census unit violation for {rid(o)}: {'; '.join(errs)}")
        k = rid(o)
        old = c["records"].get(k)
        if old:  # bytes are a property of the shape; keep the census value so only time moves GB/s
            o = dict(o, bytes_per_call=old["bytes_per_call"])
        new = gbps(o["bytes_per_call"], o["us_per_call"])
        if old and abs(new - old["gbps"]) <= c["noise_frac"] * old["gbps"]:
            continue
        rec = dict(old or {}, **o, source_row=row, result_sha256=sha, measured_at=measured_at)
        rec.pop("stale", None)
        hist = list((old or {}).get("history") or ([[old["source_row"], old["gbps"]]] if old else []))
        rec["history"] = (hist + [[row, new]])[-8:]  # trend for the dashboard: last 8 (row, GB/s)
        c["records"][k] = rec
        moved.append(k)
    c["applied"].append({"row": row, "sha256": sha})
    rerank(c)
    lines = []
    for k in moved:
        r = c["records"][k]
        frm = f"{before[k][0]:.0f} GB/s rank {before[k][1]}" if k in before else "new"
        lines.append(f"- `{row}` ({sha[:12]}): {k} {frm} -> {r['gbps']:.0f} GB/s rank {r['rank']} "
                     f"[{r['status']}, {r['recoverable_ms_per_round']:.2f} ms/round recoverable at "
                     f"{tgt(c, r):.0f} GB/s]")
    lines += [f"- `{row}` ({sha[:12]}): {n}" for n in link_seeds(c)]
    return lines


def tgt(c: dict, r: dict) -> float:
    if r.get("device") == "cpu":
        return c["cpu"]["target_frac"] * r.get("ceiling_gbps", 0.0)
    return c["target_gbps"]


def table_md(c: dict, top: int = 40) -> str:
    allr = sorted(c["records"].items(), key=lambda kv: kv[1]["rank"])
    recs = [kv for kv in allr if kv[1].get("device", "gpu") == "gpu"][:top]
    out = [BEGIN, "", "### GPU (MI210)", "", "| Rank | Model | Kernel class | Shape | n | MB/call | µs | GB/s | vs 1 TB/s | vs 1.5 TB/s | "
           "calls/round | recoverable ms/round @1.2 | Status | Seed | Source row |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in recs:
        out.append(f"| {r['rank']} | {r['model']} | {r['kernel_class']} | {r['shape']} | {r['n']} | "
                   f"{r['bytes_per_call'] / 1e6:.1f} | {r['us_per_call']:.1f} | {r['gbps']:.0f} | "
                   f"{r['gbps'] - c['floor_gbps']:+.0f} | {r['gbps'] - c['ceiling_gbps']:+.0f} | "
                   f"{r['calls_per_round']} | {r['recoverable_ms_per_round']:.2f} | {r['status']} | "
                   f"{r.get('seed', '-')} | `{r['source_row']}` |")
    cpu = c.get("cpu", CPU_DEFAULTS)
    out += ["", f"### CPU (EPYC 9655, NPS4) — open surface below {cpu['flag_frac']:.0%} of the measured ceiling "
            "(operator-tunable `cpu.flag_frac`)", "",
            "| Rank | Model | Op class | Config | MB/step | ms/step | GB/s | Ceiling GB/s | % of ceiling | Share of step | "
            f"recoverable ms @{cpu['target_frac']:.0%} | Status | Seed | Source row |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in [kv for kv in allr if kv[1].get("device") == "cpu"][:top]:
        fr = r.get("frac_of_ceiling")
        out.append(f"| {r['rank']} | {r['model']} | {r['kernel_class']} | {r.get('config', '-')} | "
                   f"{r['bytes_per_call'] / 1e6:.0f} | {r['us_per_call'] / 1e3:.2f} | {r['gbps']:.1f} | "
                   f"{r.get('ceiling_gbps', 0):.1f} | {'-' if fr is None else f'{fr:.0%}'} | "
                   f"{'-' if r.get('share_of_round') is None else format(r['share_of_round'], '.1%')} | {r['recoverable_ms_per_round']:.2f} | {r['status']} | "
                   f"{r.get('seed', '-')} | `{r['source_row']}` |")
    out += ["", END]
    return "\n".join(out)


def write_doc(path: str, c: dict) -> bool:
    txt = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    block = table_md(c)
    if BEGIN in txt and END in txt:
        new = txt[:txt.index(BEGIN)] + block + txt[txt.index(END) + len(END):]
    else:
        new = txt.rstrip("\n") + "\n\n## Generated census table\n\n" + block + "\n"
    if new != txt:
        open(path, "w", encoding="utf-8").write(new)
        return True
    return False


def append_journal(path: str, lines: list[str]) -> int:
    txt = open(path, encoding="utf-8").read()
    fresh = [ln for ln in lines if ln not in txt]
    if not fresh:
        return 0
    if JOURNAL_HEAD not in txt:
        txt = txt.rstrip("\n") + "\n\n" + JOURNAL_HEAD + "\n\n"
    i = txt.index(JOURNAL_HEAD) + len(JOURNAL_HEAD)
    j = txt.find("\n## ", i)
    j = len(txt) if j < 0 else j
    txt = txt[:j].rstrip("\n") + "\n" + "\n".join(fresh) + "\n" + txt[j:]
    open(path, "w", encoding="utf-8").write(txt)
    return len(fresh)


def write_stubs(d: str, c: dict) -> int:
    os.makedirs(d, exist_ok=True)
    n = 0
    for s in c["seed_stubs"]:
        p = os.path.join(d, re.sub(r"[^A-Za-z0-9_.-]+", "_", s["record"]) + ".md")
        if os.path.exists(p):
            continue
        open(p, "w", encoding="utf-8").write(
            f"# BW stub (generated): {s['record']}\n\nEffective {s['gbps']:.0f} GB/s < 1 TB/s floor; source "
            f"`{s['source_row']}`. **Question:** can this kernel reach >= 1.2 TB/s on MI210?\n"
            f"**Falsifier:** an op-level variant cannot exceed 1.0 TB/s at the served n -- close.\n")
        n += 1
    return n


def run(result: str, row: str | None, census: str, program: str | None, doc: str | None, seeds_out: str | None,
        dry_run: bool = False) -> dict:
    res = json.load(open(result))
    row = row or res.get("row") or os.path.basename(os.path.dirname(os.path.dirname(os.path.abspath(result))))
    sha = sha256(result)
    c = json.load(open(census)) if os.path.exists(census) else empty_census()
    obs = extract(res) + extract_cpu(res, result)
    lines = apply(c, obs, row, sha, str(res.get("at", "")))
    rep = {"row": row, "sha256": sha[:12], "observations": len(obs), "journal_lines": len(lines), "changed": False}
    if dry_run:
        rep["lines"] = lines
        return rep
    blob = json.dumps(c, indent=1, sort_keys=True) + "\n"
    old = open(census).read() if os.path.exists(census) else None
    if blob != old:
        os.makedirs(os.path.dirname(os.path.abspath(census)), exist_ok=True)
        open(census, "w").write(blob)
        rep["changed"] = True
    if doc:
        rep["doc_changed"] = write_doc(doc, c)
    if program and lines:
        rep["journal_appended"] = append_journal(program, lines)
    if seeds_out:
        rep["stubs_written"] = write_stubs(seeds_out, c)
    return rep


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--result", required=True)
    ap.add_argument("--row")
    ap.add_argument("--census", default=CENSUS)
    ap.add_argument("--program", default=None)
    ap.add_argument("--doc", default=None)
    ap.add_argument("--seeds-out", default=None)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    rep = run(a.result, a.row, a.census, a.program, a.doc, a.seeds_out, a.dry_run)
    print("BW-CENSUS " + json.dumps(rep, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
