def op_of(r: dict):
    m = OP_MAP.get((r.get("model"), r.get("kernel_class")))
    if m is None and r.get("model") == "27b-q8_0" and str(r.get("kernel_class", "")).startswith("dense_q8_"):
        m = OP_MAP[("27b-q8_0", "ffn_down_v5i")]  # extract_trace fallback class for an unlisted 27B dense Q8 shape
    return m


def device_of(path: str) -> str:
    return "cpu-quarter-24t" if path.endswith("-cpu") else "mi210"  # every CPU census row is a quarter-24t measurement


def cpu_step_ms(c: dict, model: str):  # fallback only: no served-row tok/s exists in the census (AutoKernel 2026-11-24)
    """CPU step from the census: sum(us_per_call x calls) / sum(share_of_round) over the model's n1 rows with a share
    (q38fn: the d1k depth only, so d1k and d32k are not summed together)."""
    rs = [r for r in c["records"].values() if r.get("model") == model and r.get("share_of_round") and r.get("n") == 1
          and "@" not in r.get("kernel_class", "") and not str(r.get("shape", "")).endswith("-d32k")]
    sh = sum(r["share_of_round"] for r in rs)
    return round(sum(r["us_per_call"] * r.get("calls_per_round", 1) for r in rs) / sh / 1e3, 2) if sh else None


def _pct(gb, ceil):
    return None if gb is None or not ceil else round(100.0 * gb / ceil, 1)


def derive_surfaces(c: dict) -> list[dict]:
    """Tag every record with `op`, fill GPU share_of_round from the parity shares, and (re)write c['surfaces']."""
    c["target_pct"] = TARGET_PCT
    par = c.get("parity") or {}
    refs, ops = par.get("refs", {}), {(o["path"], o["op"]): o for o in par.get("ops", [])}
    rows_by = {}
    for k, r in sorted(c["records"].items()):
        m = op_of(r)
        r["op"] = None if m is None else m[1]
        r["op_path"] = None if m is None else m[0]
        if m:
            rows_by.setdefault(m, []).append(k)
            if r.get("device", "gpu") == "gpu" and m in ops and ops[m].get("share_of_step") is not None:
                r["share_of_round"] = round(ops[m]["share_of_step"], 4)
                r["share_basis"] = "parity op share_of_step (share of the op this row measures)"
    seeds = c.get("seeds", {})
    out = []
    groups = []
    for key in list(ops) + sorted(k for k in rows_by if k not in ops):
        path, op = key
        if key in GROUP_ROLLUPS:
            continue
        o = ops.get(key, {})
        ids = rows_by.get(key, [])
        recs = [c["records"][i] for i in ids]
        dev = device_of(path)
        ceil = CEILINGS_GBPS[dev]
        recs = [r for r in recs if r.get("gbps") is not None]
        if path in STEP_MS:
            step, step_source = STEP_MS[path], "fixed: " + ("27B C18 verify round" if path.startswith("27b") else "A3B C14 busy step")
        elif path in CPU_STEP_MODEL:
            step = cpu_step_ms(c, CPU_STEP_MODEL[path])
            step_source = "derived (unverified): sum(us x calls)/sum(share_of_round), census n1 rows; no served tok/s row"
        else:
            step, step_source = None, None
        latest = max(recs, key=lambda r: (str(r.get("measured_at", "")), r["gbps"])) if recs else None
        d1k = [r for r in recs if not str(r.get("shape", "")).endswith("-d32k")]
        d32 = [r for r in recs if str(r.get("shape", "")).endswith("-d32k")]
        rep = max(d1k, key=lambda r: str(r.get("measured_at", ""))) if d1k else latest  # derived share + ours: d1k
        if rep is not None and not o:
            latest = rep
        share = o.get("share_of_step") if o else (rep or {}).get("share_of_round")
        if o.get("ours_gbps") is not None:
            ours, measured = _pct(o["ours_gbps"], ceil), True
        elif latest is not None:
            ours, measured = _pct(latest["gbps"], ceil), True
        else:
            ours, measured = None, False
        ref_key = o.get("ref") or (DERIVED_REF if not o else None)
        ref = refs.get(ref_key, {})
        ref_pct = ref.get("pct")
        covered = o.get("covered_by") or ""
        if not covered and not o:
            covered = next((s.get("covered_by", "") for s in seeds.values() for r in recs if r.get("seed") and
                            seeds.get(r["seed"]) is s), "") or ""
        saving = (None if ours is None or step is None or share is None
                  else round(step * share * max(0.0, 1 - ours / TARGET_PCT), 3))
        status = ("ok" if ours is not None and ours >= TARGET_PCT else "needs_measurement" if ours is None
                  else "covered" if covered else "open")
        out.append({
            "path": path, "op": op, "device": dev, "served": bool(o.get("served", True)),
            "share_of_step": None if share is None else round(share, 4), "step_ms": step, "step_source": step_source,
            "group": next((g[1] for g in GROUP_ROLLUPS if g[0] == path and not o), None),
            "d32k_pct": _pct(max(d32, key=lambda r: str(r.get("measured_at", "")))["gbps"], ceil) if d32 else None,
            "measured_ms": o.get("measured_ms"), "measured_ms_source": o.get("measured_ms_source"),
            "share_ms": None if share is None or step is None else round(step * share, 3),
            "ours_pct": ours, "ours_measured": measured,
            "ours_pct_placeholder": o.get("ours_pct") if not measured else None,
            "n_runs": sum(len(r.get("history") or [1]) for r in recs),
            "best_pct": _pct(max(r["gbps"] for r in recs), ceil) if recs else None,
            "latest_pct": _pct(latest["gbps"], ceil) if latest else None,
            "saving_ms_per_step": saving,
            "ref": ref_key, "ref_pct": ref_pct, "ref_status": ref.get("status") if ref_key else None,
            "gap_pp": None if ours is None or ref_pct is None else round(max(0.0, ref_pct - ours), 1),
            "covered_by": covered, "refresh_c21": bool(o.get("refresh_c21")), "status": status,
            "source": o.get("source") or ("census rows (no parity op)" if recs else None),
            "census_rows": ids})
    out.sort(key=lambda s: (s["saving_ms_per_step"] is None, -(s["saving_ms_per_step"] or 0), not s["served"],
                            s["path"], s["op"]))
    for g in sorted(GROUP_ROLLUPS):
        o = ops.get(g, {})
        mem = [x for x in out if x["group"] == g[1]]
        roll = [c["records"][i] for i in rows_by.get(g, [])]
        c.setdefault("surface_groups", {})
        groups.append({"path": g[0], "op": g[1], "parity_share_of_step": o.get("share_of_step"),
                       "class_share_sum": round(sum(x["share_of_step"] or 0 for x in mem), 4),
                       "rollup_pct": _pct(o.get("ours_gbps"), CEILINGS_GBPS[device_of(g[0])]),
                       "covered_by": o.get("covered_by") or "", "members": len(mem),
                       "census_rows": rows_by.get(g, []), "unreconciled": True,
                       "note": "roll-up of the per-class surfaces below, never ranked itself; the parity share and the "
                               "class-share sum do not reconcile and neither is vouched for"})
    # A roll-up with no per-class rows yet must still appear in the ranked table, as needs_measurement,
    # or its share silently vanishes (Flash-Next until AK-RF-C21-CENSUS-REFRESH lands the q38fn classes).
    for gr in groups:
        if gr["members"] == 0:
            dev = device_of(gr["path"])
            out.append({
                "path": gr["path"], "op": gr["op"], "device": dev, "served": True,
                "share_of_step": None, "step_ms": None, "step_source": None, "group": None, "d32k_pct": None,
                "measured_ms": None, "measured_ms_source": None, "share_ms": None,
                "ours_pct": None, "ours_measured": False, "ours_pct_placeholder": None,
                "n_runs": 0, "best_pct": None, "latest_pct": None, "saving_ms_per_step": None,
                "ref": None, "ref_pct": None, "ref_status": None, "gap_pp": None,
                "covered_by": gr["covered_by"], "refresh_c21": True, "status": "needs_measurement",
                "source": "roll-up with no per-class census rows yet; parity share "
                          f"{gr['parity_share_of_step']} not ranked (unreconciled)",
                "census_rows": gr["census_rows"]})
    for gr in groups:
        for x in out:
            if x["group"] == gr["op"]:
                x["group_covered_by"] = gr["covered_by"]  # the roll-up's owner; covered_by stays the class's own
    st = c.get("surface_stale") or {}
    for x in out:
        e = st.get(skey(x))
        if e and e.get("parity_sig") == _op_sig(c, x):
            x.update(stale=True, stale_since=e["stale_since"], stale_row=e["stale_row"])
        elif e:
            st.pop(skey(x))  # the committed parity op changed since the KEEP: the static value was refreshed
    from .census_families import op_family  # lazy: census_families imports this module
    for x in out:
        x["family"] = op_family(x["path"], x["op"])
    c["surface_groups"] = groups
    c["surfaces"] = out
    return out


HYPOTHESES_DIR = os.path.join(HERE, "seeds", "hypotheses")


def annotate(c: dict, registry: dict | None = None, hypotheses_dir: str | None = HYPOTHESES_DIR) -> None:
    """RSL-R1/R4/R7: write `coverage` (registry-derived, fail soft) and `family_rank` (surfaces + knob arms + keyed hypotheses) into c.
    Weights and knob arms come from c['model_weights'] / c['knob_arms'] when a campaign sets them; nothing is invented."""
    from . import census_coverage as cc, census_families as cf, journal_keys as jk
    for x in c.get("surfaces") or []:
        x.setdefault("family", cf.op_family(x["path"], x["op"]))
    try:
        reg = registry if registry is not None else cc.load_registry()
        c["coverage"] = {"status": "ok", **cc.coverage(c, cc.served_set(reg))} if reg else {"status": "registry-unreadable"}
    except Exception:  # noqa: BLE001 -- coverage must never crash a census write
        c["coverage"] = {"status": "registry-unreadable"}
    try:
        hyps = jk.hypothesis_entries(hypotheses_dir) if hypotheses_dir else []
    except OSError:
        hyps = []
    c["family_rank"] = cf.rank(c.get("surfaces") or [], c.get("model_weights"), c.get("knob_arms"), hyps)


def coverage_violations(c: dict) -> list[str]:
    """Served (live or planned) paths with zero census records, plus parity ops claiming served for a path the registry lacks.
    Reads c['coverage'] (annotate output); [] only when the registry was readable and every served path has a record."""
    cov = c.get("coverage") or {}
    if cov.get("status") != "ok":
        return [f"coverage unavailable: {cov.get('status', 'missing')}"]
    have = {r.get("op_path") for r in (c.get("records") or {}).values() if isinstance(r, dict)}
    out = [f"{k}: served path has zero census records" for k, v in sorted((cov.get("paths") or {}).items())
           if v["path"] not in have]
    return out + [f"{m['path']}/{m['op']}: parity op claims served, path absent from registry" for m in cov.get("mismatch") or []]


