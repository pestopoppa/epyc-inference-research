# Planner reference: the ranked surfaces as a REGENERATED journal section (replaced every run, never appended). It sits
# between SURF_BEGIN/SURF_END in the journal file; loop.program_text() lifts it out and gives it its own slot ahead of
# the 200-line journal tail, so no amount of journal growth can truncate it away.
SURF_HEAD = ("## Learnings — top bandwidth surfaces (generated by census_update.py from the census `surfaces`; "
             "regenerated every run, do not hand-edit)")
SURF_BEGIN, SURF_END = "<!-- BW-SURFACES:BEGIN generated by census_update.py -->", "<!-- BW-SURFACES:END -->"
SURF_TOP = 12


def skey(s: dict) -> str:
    return f"{s['path']}/{s['op']}"


def surfaces_md(c: dict, top: int = SURF_TOP) -> list[str]:
    """Deterministic table: top `top` by saving_ms_per_step, plus every ownerless and every needs_measurement surface."""
    surf = c.get("surfaces") or []
    if not surf:
        return []
    ranked = [s for s in surf if s.get("saving_ms_per_step") is not None]
    pick = ranked[:top]
    pick += [s for s in surf if s not in pick and (s["status"] == "needs_measurement" or
                                                     (s["status"] == "open" and not s.get("covered_by")))]
    cpu = (c.get("cpu") or CPU_DEFAULTS)["ceiling_gbps"]
    f = lambda x, fmt: "-" if x is None else format(x, fmt)
    out = [f"Target {c.get('target_pct', TARGET_PCT):.0f} % of ceiling. Ceilings: GPU MI210 {CEILINGS_GBPS['mi210']:.0f} GB/s, "
           f"CPU quarter-24t {cpu.get('quarter-24t', 129.0):.0f} GB/s, CPU full host {cpu.get('full-host', 520.0):.0f} GB/s. "
           "saving = step_ms x share x max(0, 1 - ours/target). Owner **none** = no box/row/seed works it: propose there first. "
           "STALE = a KEEP touched a parity-only surface; its ours % predates that KEEP, re-measure before ranking on it.",
           "", "| # | Op · path | Family | Share | Ours % | Saving ms/step | Owner | Status | Step source |", "|---|---|---|---|---|---|---|---|---|"]
    for i, s in enumerate(pick, 1):
        st = s["status"] + (f" STALE since {s['stale_since']} ({s['stale_row']})" if s.get("stale") else "")
        out.append(f"| {i} | {s['op']} · {s['path']} | {s.get('family') or '-'} | {f(s['share_of_step'], '.1%')} | "
                   f"{f(s['ours_pct'], '.1f')}{'' if s['ours_measured'] or s['ours_pct'] is None else ' (placeholder)'} | "
                   f"{f(s['saving_ms_per_step'], '.2f')} | {s.get('covered_by') or '**none**'} | {st} | {s.get('step_source') or '-'} |")
    out += _family_rank_md(c, f)
    return out


def _family_rank_md(c: dict, f) -> list[str]:
    fr = c.get("family_rank") or []
    if not fr:
        return []
    out = ["", "Family rank (score = sum of weight x saving ms/step over every path; `-` = unpriced, never guessed; "
           "knob = serving-knob arm, hypothesis = hand-written idea priced from census rows on every device it touches):",
           "", "| # | Family | Kind | Score ms/step | Paths | Unpriced |", "|---|---|---|---|---|---|"]
    for i, r in enumerate(fr[:SURF_TOP + 8], 1):
        paths = sorted({m["path"] for m in r["members"] if m.get("path")} | ({r["path"]} if r.get("path") else set()))
        out.append(f"| {i} | {r['family']} | {r['kind']} | {f(r['score'], '.2f')} | {', '.join(paths) or '-'} | "
                   f"{r.get('n_unpriced', 0 if r['status'] == 'priced' else 1)} |")
    return out


def write_surfaces_block(path: str, c: dict) -> bool:
    """Replace the generated surfaces section in the journal file (insert it ahead of the journal section once)."""
    txt = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    body = surfaces_md(c)
    if not body:
        return False
    block = SURF_BEGIN + "\n" + SURF_HEAD + "\n\n" + "\n".join(body) + "\n" + SURF_END
    if SURF_BEGIN in txt and SURF_END in txt:
        new = txt[:txt.index(SURF_BEGIN)] + block + txt[txt.index(SURF_END) + len(SURF_END):]
    elif JOURNAL_HEAD in txt:
        i = txt.index(JOURNAL_HEAD)
        new = txt[:i] + block + "\n\n" + txt[i:]
    else:
        new = txt.rstrip("\n") + ("\n\n" if txt else "") + block + "\n"
    if new != txt:
        open(path, "w", encoding="utf-8").write(new)
        return True
    return False


# Per-surface seeds (AutoKernel 2026-11-24): ONE seed per open, measured surface with no owner of its own
