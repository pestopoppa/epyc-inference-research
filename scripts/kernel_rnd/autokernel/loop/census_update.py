# Placeholder rule (ours_measured): ours_pct is MEASURED when it comes from a bandwidth number -- the parity op's
# `ours_gbps` (from a named trace/row) or, absent that, the latest mapped census row. A parity op that states only a bare
# `ours_pct` (no ours_gbps) and has no mapped census rows is a PLACEHOLDER (today: the 35 % launch-bound / fused-tail ops):
# ours_measured=false, ours_pct=null, saving null, status needs_measurement; the stated value is kept as ours_pct_placeholder.
# Decided from provenance (which field carried it, which rows map), never from the value.

