def sha256(path: str) -> str:
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def empty_census() -> dict:
    return {"cpu": json.loads(json.dumps(CPU_DEFAULTS)), "schema": "epyc.autokernel.bw_census.v1", "floor_gbps": FLOOR, "target_gbps": TARGET,
            "ceiling_gbps": CEILING, "noise_frac": NOISE, "records": {}, "seeds": {}, "seed_stubs": [],
            "applied": []}


def rid(o: dict) -> str:
    if o.get("device") == "cpu":
        return f"cpu|{o['model']}|{o['kernel_class']}|{o['shape']}|n{o['n']}"
    return f"{o['model']}|{o['kernel_class']}|{o['shape']}|n{o['n']}"


def gbps(b: float, us: float) -> float:
    return round(b / (us * 1e3), 1) if us > 0 else 0.0


def recoverable_ms(r: dict, target: float) -> float:
    ideal_us = r["bytes_per_call"] / (target * 1e3)
    return round(max(0.0, r["us_per_call"] - ideal_us) * r["calls_per_round"] / 1e3, 3)


def apply_ceilings(c: dict) -> None:
    """Force the operator-set ceilings (2026-11-24) onto a census, including a live file that predates them."""
    c["ceiling_gbps"] = CEILINGS_GBPS["mi210"]
    cpu = c.setdefault("cpu", json.loads(json.dumps(CPU_DEFAULTS)))
    for k in ("quarter-24t", "full-host"):
        cpu.setdefault("ceiling_gbps", {})[k] = CPU_DEFAULTS["ceiling_gbps"][k]
        cpu.setdefault("ceiling_source", {})[k] = CPU_DEFAULTS["ceiling_source"][k]


def rerank(c: dict) -> None:
    recs = c["records"]
    apply_ceilings(c)
    cpu = c["cpu"]
    for r in recs.values():
        if r.get("bytes_per_call") is None or r.get("us_per_call") is None:
            continue  # malformed/foreign record: leave untouched, never crash a merge
        r["gbps"] = gbps(r["bytes_per_call"], r["us_per_call"])
        floor, target = c["floor_gbps"], c["target_gbps"]
        if r.get("device") == "cpu":
            ceil = cpu["ceiling_gbps"].get(r.get("config", ""), 0.0)
            floor, target = cpu["flag_frac"] * ceil, cpu["target_frac"] * ceil
            r["ceiling_gbps"] = ceil
            r["frac_of_ceiling"] = round(r["gbps"] / ceil, 3) if ceil else None
        r["status"] = ("stale" if r.get("stale") else "no_ceiling" if floor <= 0
                       else "open_surface" if r["gbps"] < floor else "ok")
        r["recoverable_ms_per_round"] = recoverable_ms(r, target) if target > 0 else 0.0
    for dev in ("gpu", "cpu"):  # ranks are per device
        order = sorted((k for k in recs if recs[k].get("device", "gpu") == dev),
                       key=lambda k: (-recs[k].get("recoverable_ms_per_round", 0.0), k))
        for i, k in enumerate(order, 1):
            recs[k]["rank"] = i


def link_seeds(c: dict) -> list[str]:
    """Mark seeds done and emit stubs for unlinked open surfaces. Returns journal fragments."""
    notes = []
    recs = c["records"]
    for sid, s in sorted(c["seeds"].items()):
        linked = [r for k, r in recs.items() if all(r.get(f) == v for f, v in s.get("match", {}).items())
                  and r["n"] in s.get("n", sorted(SERVED_N))]
        bar = float(s.get("target_gbps", c["floor_gbps"]))
        if s.get("device", "gpu") == "gpu":
            bar = max(c["floor_gbps"], bar)
        if linked and s.get("status") != "done" and all(r["gbps"] >= bar for r in linked):
            s["status"] = "done"
            notes.append(f"seed {sid} DONE (all {len(linked)} linked records >= {bar:.0f} GB/s)")
        for r in linked:
            r["seed"] = sid
    have = {x["record"] for x in c["seed_stubs"]}
    for k in sorted(recs):
        r = recs[k]
        if r["status"] == "open_surface" and not r.get("seed") and k not in have:
            c["seed_stubs"].append({"record": k, "gbps": r["gbps"], "source_row": r["source_row"]})
            notes.append(f"seed stub for {k} ({r['gbps']:.0f} GB/s < floor, no linked seed)")
    return notes


def apply_time_only(c: dict, o: dict, row: str, sha: str, at: str) -> bool:
    """Observation with NO derivable byte basis (bytes_per_call None): kept under c['time_only'] (time, no GB/s, no rank, no seed).
    Same noise rule as bandwidth records; returns True when it moved."""
    k, old = rid(o), c.setdefault("time_only", {}).get(rid(o))
    if old and abs(o["us_per_call"] - old["us_per_call"]) <= c["noise_frac"] * abs(old["us_per_call"]):
        return False
    hist = list((old or {}).get("history") or ([[old["source_row"], old["us_per_call"]]] if old else []))
    c["time_only"][k] = dict(o, source_row=row, result_sha256=sha, measured_at=at, history=(hist + [[row, o["us_per_call"]]])[-8:])
    return True


def apply(c: dict, obs: list[dict], row: str, sha: str, measured_at: str) -> list[str]:
    """Pure-ish: mutate census c, return journal lines. No-op when sha already applied."""
    if any(a["sha256"] == sha for a in c["applied"]):
        return []
    rerank(c)
    before = {k: (r["gbps"], r["rank"]) for k, r in c["records"].items()}
    moved, tmoved = [], 0
    for o in obs:
        if o.get("bytes_per_call") is None:
            tmoved += apply_time_only(c, o, row, sha, measured_at)
            continue
        o = dict(o, unit=o.get("unit") or "GB/s")  # every census extractor emits bytes/us => GB/s; flops rows set unit
        if errs := validate_unit(o):
            raise ValueError(f"census unit violation for {rid(o)}: {'; '.join(errs)}")
        k = rid(o)
        if o.get("split_from") and (lump := c["records"].pop(rid(dict(o, kernel_class=o["split_from"])), None)):  # lumped record -> classifier_split
            o = dict(o, superseded=list(lump.get("superseded") or []) + [{
                "validity": "classifier_split", "source_row": lump["source_row"], "result_sha256": lump["result_sha256"],
                "gbps": lump["gbps"], "us_per_call": lump["us_per_call"], "superseded_by": {"row": row, "sha256": sha},
                "reason": f"{o['split_from']} lumped the indexer score GEMM (no counted bytes) with the weight GEMVs; split by node"}])
        old = c["records"].get(k)
        if old:  # bytes are a property of the shape; keep the census value so only time moves GB/s
            o = dict(o, bytes_per_call=old["bytes_per_call"])
        new = gbps(o["bytes_per_call"], o["us_per_call"])
        quiet_over_contended = bool(old and o.get("quiet_host") and not old.get("quiet_host"))
        if old and old.get("quiet_host") and not o.get("quiet_host"):
            continue  # a contended/unguarded measurement never displaces a quiet-host one
        if old and not quiet_over_contended and abs(new - old["gbps"]) <= c["noise_frac"] * old["gbps"]:
            continue
        rec = dict(old or {}, **o, source_row=row, result_sha256=sha, measured_at=measured_at)
        rec.pop("stale", None)
        if quiet_over_contended:  # same op/shape: the guarded quiet-host value supersedes, the old one is kept as invalid
            rec["superseded"] = list(old.get("superseded") or []) + [{
                "validity": "contention_invalid", "source_row": old["source_row"], "result_sha256": old["result_sha256"],
                "gbps": old["gbps"], "us_per_call": old["us_per_call"], "superseded_by": {"row": row, "sha256": sha},
                "reason": "unguarded measurement superseded by a guarded quiet-host measurement of the same op/shape"}]
        hist = list((old or {}).get("history") or ([[old["source_row"], old["gbps"]]] if old else []))
        rec["history"] = (hist + [[row, new]])[-8:]  # trend for the dashboard: last 8 (row, GB/s)
        c["records"][k] = rec
        moved.append(k)
    c["applied"].append({"row": row, "sha256": sha})
    rerank(c)
    derive_surfaces(c)
    lines = []
    for k in moved:
        r = c["records"][k]
        frm = f"{before[k][0]:.0f} GB/s rank {before[k][1]}" if k in before else "new"
        frm += " [supersedes contention_invalid]" if k in before and r.get("superseded") and r["superseded"][-1]["superseded_by"]["sha256"] == sha else ""
        lines.append(f"- `{row}` ({sha[:12]}): {k} {frm} -> {r['gbps']:.0f} GB/s rank {r['rank']} "
                     f"[{r['status']}, {r['recoverable_ms_per_round']:.2f} ms/round recoverable at "
                     f"{tgt(c, r):.0f} GB/s]")
    lines += [f"- `{row}` ({sha[:12]}): {n}" for n in link_seeds(c)]
    return lines + ([f"- `{row}` ({sha[:12]}): {tmoved} time-only records (bytes unknown) stored under census time_only"] if tmoved else [])


def tgt(c: dict, r: dict) -> float:
    if r.get("device") == "cpu":
        return c["cpu"]["target_frac"] * r.get("ceiling_gbps", 0.0)
    return c["target_gbps"]


def parity_rows(c: dict) -> list[dict]:
    """Roofline-parity view: ours % vs best published reference %, gap x share of step (pp)."""
    p = c.get("parity") or {}
    refs, rows = p.get("refs", {}), []
    for o in p.get("ops", []):
        ref = refs.get(o["ref"], {})
        ours = o.get("ours_pct")
        if ours is None and o.get("ours_gbps") is not None:
            ours = 100.0 * o["ours_gbps"] / o["roofline_gbps"]
        ref_pct = ref.get("pct")  # null = no published measurement: no gap, no score (never read as 0 %)
        gap = None if ours is None or ref_pct is None else max(0.0, ref_pct - ours)
        sh = o.get("share_of_step")
        score = None if gap is None or sh is None else gap * sh
        rows.append({**o, "ours": ours, "ref_pct": ref_pct, "gap": gap, "score": score})
    rows.sort(key=lambda r: (not r["served"], -(r["score"] or -1)))
    return rows


def parity_md(c: dict) -> list[str]:
    rows = parity_rows(c)
    if not rows:
        return []
    f = lambda x, s: "-" if x is None else format(x, s)
    out = ["", "### Roofline parity (gap x share of step)", "", c["parity"].get("note", ""), "",
           "| # | Path | Op | Ours % roofline | Best ref % | Ref | Gap pp | Share of step | Score (pp) | Covered by | C21 refresh | Source |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        out.append(f"| {i} | {r['path']}{'' if r['served'] else ' (not served)'} | {r['op']} | {f(r['ours'], '.0f')} | "
                   f"{'no published measurement' if r['ref_pct'] is None else f(r['ref_pct'], '.0f')} | {r['ref']} | {f(r['gap'], '.0f')} | {f(r['share_of_step'], '.1%')} | "
                   f"{f(r['score'], '.1f')} | {r['covered_by'] or '**none**'} | {'yes' if r['refresh_c21'] else '-'} | {r['source']} |")
    top = [r for r in rows if r["served"] and not r["covered_by"] and r["score"]][:5]
    out += ["", "Top unworked gaps (served, no box or row): " + "; ".join(
        f"{r['path']} {r['op']} ({r['score']:.1f})" for r in top), "", "References:", ""]
    out += [f"- `{k}` {'no published measurement' if v['pct'] is None else str(v['pct']) + '%'}"
            f"{'' if not v.get('bracket_pct') else ' (brackets, end-to-end: ' + ', '.join(f'{b} {x}%' for b, x in v['bracket_pct'].items()) + ')'}"
            f" [{v.get('status', 'recalled, not re-verified')}] ({v['basis']}): {v['cite']}"
            for k, v in sorted(c["parity"].get("refs", {}).items())]
    bd = c["parity"].get("batch_dependence")
    if bd:
        out += ["", "Batch dependence of reference %-of-peak: " + bd["note"] + f" Source: {bd['source']}.", "",
                "| Kernel | % of peak | Batch |", "|---|---|---|"]
        out += [f"| {x['kernel']} | {x['pct']} | {x['batch']} |" for x in bd["rows"]]
    return out


def table_md(c: dict, top: int = 40) -> str:
    allr = sorted(c["records"].items(), key=lambda kv: kv[1]["rank"])
    recs = [kv for kv in allr if kv[1].get("device", "gpu") == "gpu"][:top]
    out = [BEGIN, "", "### GPU (MI210)", "", "| Rank | Model | Kernel class | Shape | n | MB/call | µs | GB/s | vs 1 TB/s | vs 1.5 TB/s | "
           "calls/round | recoverable ms/round @1.2 | Status | Seed | Source row |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in recs:
        out.append(f"| {r['rank']} | {r['model']} | {r['kernel_class']} | {r['shape']} | {r['n']} | "
                   f"{r['bytes_per_call'] / 1e6:.1f} | {r['us_per_call']:.1f} | {r['gbps']:.0f} | "
                   f"{r['gbps'] - c['floor_gbps']:+.0f} | {r['gbps'] - c['ceiling_gbps']:+.0f} | "
                   f"{r['calls_per_round']} | {r['recoverable_ms_per_round']:.2f} | {r['status']} | "
                   f"{r.get('seed', '-')} | `{r['source_row']}` |")
    cpu = c.get("cpu", CPU_DEFAULTS)
    out += ["", f"### CPU (EPYC 9655, NPS4) — open surface below {cpu['flag_frac']:.0%} of the measured ceiling "
            "(operator-tunable `cpu.flag_frac`)", "",
            "| Rank | Model | Op class | Config | MB/step | ms/step | GB/s | Ceiling GB/s | % of ceiling | Share of step | "
            f"recoverable ms @{cpu['target_frac']:.0%} | Status | Seed | Source row |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in [kv for kv in allr if kv[1].get("device") == "cpu"][:top]:
        fr = r.get("frac_of_ceiling")
        out.append(f"| {r['rank']} | {r['model']} | {r['kernel_class']} | {r.get('config', '-')} | "
                   f"{r['bytes_per_call'] / 1e6:.0f} | {r['us_per_call'] / 1e3:.2f} | {r['gbps']:.1f} | "
                   f"{r.get('ceiling_gbps', 0):.1f} | {'-' if fr is None else f'{fr:.0%}'} | "
                   f"{'-' if r.get('share_of_round') is None else format(r['share_of_round'], '.1%')} | {r['recoverable_ms_per_round']:.2f} | {r['status']} | "
                   f"{r.get('seed', '-')} | `{r['source_row']}` |")
    out += parity_md(c)
    sm = surfaces_md(c)
    if sm:
        out += ["", "### Bandwidth surfaces (ranked by saving ms/step)", ""] + sm
    out += ["", END]
    return "\n".join(out)


def write_doc(path: str, c: dict) -> bool:
    txt = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    block = table_md(c)
    if BEGIN in txt and END in txt:
        new = txt[:txt.index(BEGIN)] + block + txt[txt.index(END) + len(END):]
    else:
        new = txt.rstrip("\n") + "\n\n## Generated census table\n\n" + block + "\n"
    if new != txt:
        open(path, "w", encoding="utf-8").write(new)
        return True
    return False


def append_journal(path: str, lines: list[str]) -> int:
    txt = open(path, encoding="utf-8").read()
    fresh = [ln for ln in lines if ln not in txt]
    if not fresh:
        return 0
    if JOURNAL_HEAD not in txt:
        txt = txt.rstrip("\n") + "\n\n" + JOURNAL_HEAD + "\n\n"
    i = txt.index(JOURNAL_HEAD) + len(JOURNAL_HEAD)
    j = txt.find("\n## ", i)
    j = len(txt) if j < 0 else j
    txt = txt[:j].rstrip("\n") + "\n" + "\n".join(fresh) + "\n" + txt[j:]
    open(path, "w", encoding="utf-8").write(txt)
    return len(fresh)


def write_stubs(d: str, c: dict) -> int:
    """ONE stub per seedable surface (open, measured, no owner) -- never per census record (AutoKernel 2026-11-24: the
    per-n record stubs stay a journal note only). The stub dir is a preview; the loop reads nothing here. The committed
    seed is `loop/seeds/hypotheses/NN-bw-surfaces-<date>.md`, produced by --surface-seeds-out and committed by review."""
    os.makedirs(d, exist_ok=True)
    n = 0
    for s in seedable_surfaces(c):
        p = os.path.join(d, surface_seed_id(s) + ".md")
        body = "\n".join(surface_seed_section(s, c)) + "\n"
        if os.path.exists(p) and open(p, encoding="utf-8").read() == body:
            continue
        open(p, "w", encoding="utf-8").write(body)
        n += 1
    return n


